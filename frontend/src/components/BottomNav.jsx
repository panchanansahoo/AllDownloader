export default function BottomNav({ currentTab, setCurrentTab }) {
  const { downloads } = useDownload();
  const activeDownloads = downloads.filter(d => d.status === 'downloading').length;

  const navItems = [
    { id: "home", label: "Home", icon: <HomeIcon /> },
    { id: "downloads", label: "Downloads", icon: <DownloadIcon />, badge: activeDownloads },
    { id: "library", label: "Library", icon: <LibraryIcon /> },
    { id: "settings", label: "Settings", icon: <SettingsIcon /> },
  ];

  return (
    <nav className="fixed bottom-0 left-0 right-0 z-50 border-t border-slate-200 bg-white/80 pb-safe backdrop-blur-xl dark:border-slate-800 dark:bg-slate-950/80 sm:hidden">
      <div className="flex h-16 justify-around items-center px-2">
        {navItems.map((item) => {
          const isActive = currentTab === item.id;
          return (
            <button
              key={item.id}
              onClick={() => setCurrentTab(item.id)}
              className={`relative flex flex-col items-center justify-center w-full h-full transition-colors ${isActive ? 'text-blue-600 dark:text-blue-400' : 'text-slate-500 hover:text-slate-900 dark:text-slate-400 dark:hover:text-slate-100'}`}
            >
              <div className="relative">
                {item.icon}
                {item.badge > 0 && (
                  <span className="absolute -top-1 -right-2 flex h-4 w-4 items-center justify-center rounded-full bg-blue-600 text-[10px] font-bold text-white">
                    {item.badge}
                  </span>
                )}
              </div>
              <span className="mt-1 text-[10px] font-medium">{item.label}</span>
            </button>
          );
        })}
      </div>
    </nav>
  );
}
